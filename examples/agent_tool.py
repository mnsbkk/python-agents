import asyncio              # Required to run asynchronous code (the main event loop)
import os                   # To interact with the operating system (reading environment variables)
import random               # Used to generate a random number for the mock weather data
from pathlib import Path    # Object-oriented filesystem paths, used to safely locate the .env file

# Import the core components from Microsoft's Agent Framework
from agent_framework import Agent, tool  # 'Agent' manages the conversation, 'tool' exposes Python functions to Gemini
# Import the Gemini integration for the Agent Framework
from agent_framework_gemini import GeminiChatClient 
from dotenv import load_dotenv           # To load variables from our .env file
from rich import print                   # A prettier replacement for the standard print()

# --- 1. ENVIRONMENT VARIABLES ---
# Create a Path object pointing to the .env file located one directory up from this script
env_path = Path(__file__).resolve().parent.parent / ".env"
# Load the .env file. override=True ensures it overrides any existing system environment variables
load_dotenv(dotenv_path=env_path, override=True)

# Safety check: Make sure the Google API key is actually loaded before proceeding
if not os.environ.get("GOOGLE_API_KEY"):
    print("[bold red]Error:[/bold red] GOOGLE_API_KEY is not set in your .env file.")
    exit(1) # Exit the script with an error code 1 if the key is missing

# --- 2. INITIALIZE THE AI CLIENT ---
# Initialize the Gemini client. It automatically reads GOOGLE_API_KEY and GOOGLE_MODEL from the environment
client = GeminiChatClient()


# --- 3. DEFINE THE TOOL ---
# The @tool decorator automatically parses the function signature, type hints, and docstrings
# and converts them into the JSON Schema that Gemini expects.
@tool
def get_weather(city: str) -> dict:
    """Returns weather data for a given city, a dictionary with temperature and description.
    
    Args:
        city: City name, spelled out fully.
    """
    # Print a message to the terminal so we know the AI successfully triggered this tool
    print(f"[bold yellow]Executing tool: get_weather for {city}...[/bold yellow]")
    
    # Randomly return Sunny (5% chance) or Rainy (95% chance) to test the AI's dynamic logic
    if random.random() < 0.05:
        return {
            "temperature": 72,
            "description": "Sunny",
        }
    else:
        return {
            "temperature": 60,
            "description": "Rainy",
        }


# --- 4. CREATE THE AGENT ---
# The Agent acts as the orchestrator. It holds the client, system instructions, and available tools.
agent = Agent(
    client=client, 
    instructions="You're an informational agent. Answer questions cheerfully.", 
    tools=[get_weather] # We pass the tool we defined above so the AI knows it exists
)


# --- 5. THE MAIN EXECUTION LOOP ---
async def main():
    print("[bold cyan]User Prompt:[/bold cyan] how's weather today in ca?")
    
    # The agent.run() method handles the entire ReAct (Reasoning and Acting) loop automatically:
    # 1. It sends the user prompt + tool definitions to Gemini.
    # 2. Gemini decides it needs to know the weather and replies with a function call request.
    # 3. The framework executes our local get_weather function.
    # 4. The framework sends the result back to Gemini.
    # 5. Gemini generates a final, cheerful natural language response.
    response = await agent.run(input("Prompt: "))
    
    # Print the final natural language response generated by Gemini
    print("\n[bold green]Final Response:[/bold green]")
    print(response.text)


# --- 6. ENTRY POINT ---
if __name__ == "__main__":
    # Start the asyncio event loop and run the main() function
    asyncio.run(main())